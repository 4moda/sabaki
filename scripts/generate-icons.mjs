import { execFileSync } from 'node:child_process'
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'

const ROOT = resolve(import.meta.dirname, '..')
const BUILD_DIR = join(ROOT, 'build')
const MAIN_ELECTRON_DIR = join(ROOT, 'src/main/infrastructure/electron')
const RENDERER_PUBLIC_DIR = join(ROOT, 'src/renderer/public')

const MASTER_SVG = join(BUILD_DIR, 'icon.svg')
const TRAY_COLOR_SVG = join(BUILD_DIR, 'tray-icon.svg')
const TRAY_TEMPLATE_SVG = join(BUILD_DIR, 'tray-icon-template.svg')

function renderSvgToPng(svgPath, size, outPath) {
  execFileSync('rsvg-convert', ['-w', String(size), '-h', String(size), svgPath, '-o', outPath], {
    stdio: 'inherit'
  })
}

/**
 * Builds a standard Apple ICNS file from PNG buffers using modern PNG-in-ICNS chunk types
 * (icp4=16, icp5=32, icp6=64, ic07=128, ic08=256, ic09=512, ic10=1024).
 */
function buildIcnsBuffer(entries) {
  const chunks = entries.map(({ type, data }) => {
    const header = Buffer.alloc(8)
    header.write(type, 0, 4, 'ascii')
    header.writeUInt32BE(8 + data.length, 4)
    return Buffer.concat([header, data])
  })

  const totalSize = 8 + chunks.reduce((sum, chunk) => sum + chunk.length, 0)
  const fileHeader = Buffer.alloc(8)
  fileHeader.write('icns', 0, 4, 'ascii')
  fileHeader.writeUInt32BE(totalSize, 4)
  return Buffer.concat([fileHeader, ...chunks])
}

/**
 * Builds a Windows ICO file using ImageMagick (`convert`) so legacy NSIS/rcedit
 * consumers receive compatible BMP/PNG icon entries across all standard sizes.
 */
function buildIcoFile(pngPaths, outPath) {
  execFileSync('convert', [...pngPaths, outPath], { stdio: 'inherit' })
}

function toPngDataUrl(pngBuffer) {
  return `data:image/png;base64,${pngBuffer.toString('base64')}`
}

function main() {
  const workDir = mkdtempSync(join(tmpdir(), 'sabaki-icons-'))

  try {
    // 1. Render master app icon sizes
    const appSizes = [16, 24, 32, 48, 64, 128, 256, 512, 1024]
    const appPngPaths = new Map()
    for (const size of appSizes) {
      const outPath = join(workDir, `icon-${size}.png`)
      renderSvgToPng(MASTER_SVG, size, outPath)
      appPngPaths.set(size, outPath)
    }

    // Save 1024x1024 master PNG for electron-builder
    copyFileSync(appPngPaths.get(1024), join(BUILD_DIR, 'icon.png'))

    // 2. Build Windows multi-size ICO (16, 24, 32, 48, 64, 128, 256)
    const icoSizes = [16, 24, 32, 48, 64, 128, 256]
    buildIcoFile(
      icoSizes.map((s) => appPngPaths.get(s)),
      join(BUILD_DIR, 'icon.ico')
    )

    // 3. Build macOS ICNS (16, 32, 64, 128, 256, 512, 1024)
    const icnsMap = [
      { type: 'icp4', size: 16 },
      { type: 'icp5', size: 32 },
      { type: 'icp6', size: 64 },
      { type: 'ic07', size: 128 },
      { type: 'ic08', size: 256 },
      { type: 'ic09', size: 512 },
      { type: 'ic10', size: 1024 }
    ]
    const icnsBuf = buildIcnsBuffer(
      icnsMap.map(({ type, size }) => ({
        type,
        data: readFileSync(appPngPaths.get(size))
      }))
    )
    writeFileSync(join(BUILD_DIR, 'icon.icns'), icnsBuf)

    // 4. Render tray icons (1x = 16px, 2x = 32px) for color & macOS template
    const trayColor1x = join(workDir, 'tray-color-16.png')
    const trayColor2x = join(workDir, 'tray-color-32.png')
    const trayTemplate1x = join(workDir, 'tray-template-16.png')
    const trayTemplate2x = join(workDir, 'tray-template-32.png')

    renderSvgToPng(TRAY_COLOR_SVG, 16, trayColor1x)
    renderSvgToPng(TRAY_COLOR_SVG, 32, trayColor2x)
    renderSvgToPng(TRAY_TEMPLATE_SVG, 16, trayTemplate1x)
    renderSvgToPng(TRAY_TEMPLATE_SVG, 32, trayTemplate2x)

    // 5. Generate inline Electron runtime asset module (zero external file path issues inside asar)
    const tsContent = `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-icons.mjs from build/icon.svg, build/tray-icon.svg, build/tray-icon-template.svg
// Design: Sabaki "Sabatora Paw Card Sorting" (猫の手カードさばき)

export const APP_WINDOW_ICON_PNG_DATA_URL =
  '${toPngDataUrl(readFileSync(appPngPaths.get(256)))}'

export const TRAY_COLOR_ICON_1X_DATA_URL =
  '${toPngDataUrl(readFileSync(trayColor1x))}'

export const TRAY_COLOR_ICON_2X_DATA_URL =
  '${toPngDataUrl(readFileSync(trayColor2x))}'

export const TRAY_TEMPLATE_ICON_1X_DATA_URL =
  '${toPngDataUrl(readFileSync(trayTemplate1x))}'

export const TRAY_TEMPLATE_ICON_2X_DATA_URL =
  '${toPngDataUrl(readFileSync(trayTemplate2x))}'
`
    writeFileSync(join(MAIN_ELECTRON_DIR, 'appIconAssets.ts'), tsContent, 'utf8')

    // 6. Copy favicon.svg into renderer public assets
    mkdirSync(RENDERER_PUBLIC_DIR, { recursive: true })
    copyFileSync(MASTER_SVG, join(RENDERER_PUBLIC_DIR, 'favicon.svg'))

    console.log('Generated icon assets successfully:')
    console.log(' - build/icon.png (1024x1024)')
    console.log(' - build/icon.ico (16/24/32/48/64/128/256)')
    console.log(' - build/icon.icns (16/32/64/128/256/512/1024)')
    console.log(' - src/main/infrastructure/electron/appIconAssets.ts')
    console.log(' - src/renderer/public/favicon.svg')
  } finally {
    rmSync(workDir, { recursive: true, force: true })
  }
}

main()
